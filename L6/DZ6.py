#1 Користувач вводить розмір футболки(S, M, L або XL).
#Якщо введено S або M – спитайте колір футболки(немає фіолетових і жовтих)
#Якщо введено L – повідомте що всі футболки цього розміру закінчились
#Якщо введено XL – спитайте тип тканини(є лише бавовна)
#В результаті програма повинна вивести «Є в наявності» або «Немає в наявності

shirt = input("Введіть розмір футболки: (S, M, L або XL) ")

if shirt == "S" or shirt == "M":
    color = input("Який колір футболки (немає фіолетових і жовтих) ")
    if color == "фіолетова" or color == "жовта":
        print("Немає в наявності")

    else:
        print("Є в наявності")

elif shirt == "XL":
    fabric_type = input("Який тип тканини: ")
    if fabric_type == "бавовна":
        print("Є в наявності")

    else:
        print("Немає в наявності")
        
else:
    print("Немає в наявності")


