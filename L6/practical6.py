#7 Користувач вводить швидкість.
# Якщо швидкість більша за 90км\год – спитати де саме він
# їде: місто чи траса.
# Якщо в місті то повідомити про штраф,
# якщо траса то попередження
# Якщо швидкість менша за 20км/год – спитати скільки років машині.
# Якщо їй більше 15 років – запропонувати купити нову, інакше запропонувати поїхати на СТО
# Інша швидкість – побажати гарної подорожі.


speed = int(input("Введіть швидкість: "))

if speed >=  90:
    location = input("Ти де: місто/траса ?: ")
    if location == "місто":
        print("У Вас штраф за перевищення швидкоті")
    elif location == "траса":
        print("У Вас попередження швідкісного контролю")

elif speed <= 20:
    age = int(input("Скільки років машині?: "))
    if age >= 15:
        print("Купи нове авто")
    elif age <= 15:
        print("Проїдь на СТО")

else:
    print("Бажаю гарної подорожі!")