# Написати програму для конвертації валют.
# Користувачу пропонується меню
# 1. долари
# 2. євро
# 3. єни
# 4. вихід
# Після чого користувач вводить суму в гривнях,
# а програма переводить їх в обрану валюту

USD_RATE = 45.49
EURO_RATE = 50.2649
JPY_RATE = 0.27198

# вивести меню
print("1. долари")
print("2. євро")
print("3. єни")
print("4. вихід")

while True:
    # введення самої команди
    command = int(input("виберіть номер команди: "))

    # перевірка на вихід
    if command == 4:
        print("програма завершена")
        break

    # перевірка чи номер команди правильний
    if command < 1 or command > 4:
        print("ви ввели неправильне число")
        continue

    # основна програма
    uah = float(input("ВВедіть суму у гривнях: "))

    # перевірка чи правильне число
    if uah < 0:
        print("Ввивели неправильну суму")
        continue

    # перевірямо вибір користувача
    if command == 1:
        rate = USD_RATE
        symbol = "$"
    elif command == 2:
        rate = EURO_RATE
        symbol = "євро"
    else:
        rate = JPY_RATE
        symbol = "єн"

    result = uah / rate
    print(f"Це буде {result:.2f} {symbol}")
    print()
