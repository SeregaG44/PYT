pillow = 650 # подушка – 650 грн
blanket = 1700 # ● ковдра – 1700 грн
lamp = 500 # ● лампа – 500 грн
keychain = 60 # ● брелок – 60 грн
check = 0
goods = ""

while True:
    menu = int(input("Виберіть будь ласка дію (1-5) "))

    if menu == 5:
        print("До нових зустрічей")
        break

    if menu == 1:
        shop = input("Виберіть товар: ")

        if shop == "подушка":
            check += pillow
            goods += "подушка"

        elif shop == "ковдра":
            check += blanket
            goods += "ковдра"

        elif shop == "лампа":
            check += lamp
            goods += "лампа"

        elif shop == "брелок":
            check += keychain
            goods += "брелок"

        else:
            print("Такого товара немає ")

    if menu == 2:
        shop = input("Виберіть товар: ")

        if shop == "подушка":
            check -= pillow

        elif shop == "ковдра":
            check -= blanket

        elif shop == "лампа":
            check -= lamp

        elif shop == "брелок":
            check -= keychain

        else:
            print("Такого товара немає ")

    if menu == 3:
        check = 0
        goods = ""
        print("Кошик очіщен")

    if menu == 4:
        print(f"Ви обрали: {goods}, \nСумма Вашої покупки {check} грн")










