pillow = 650  # подушка – 650 грн
blanket = 1700  # ● ковдра – 1700 грн
lamp = 500  # ● лампа – 500 грн
keychain = 60  # ● брелок – 60 грн
check = 0
goods = ""

while True:
    menu = int(input("Виберіть будь ласка дію (1-5) "))

    if menu == 5:
        print("До нових зустрічей")
        break

    elif menu == 1:
        shop = input("Виберіть товар: ")
        quantity_goods = int(input("Введіть кількість: "))

        if shop == "подушка":
            check += pillow * quantity_goods
            goods += "подушка\n"

        elif shop == "ковдра":
            check += blanket * quantity_goods
            goods += "ковдра\n"

        elif shop == "лампа":
            check += lamp * quantity_goods
            goods += "лампа\n"

        elif shop == "брелок":
            check += keychain * quantity_goods
            goods += "брелок\n"

        else:
            print("Такого товара немає ")

    elif menu == 2:
        shop = input("Виберіть товар: ")

        if shop == "подушка":
            check -= pillow

        elif shop == "ковдра":
            check -= blanket

        elif shop == "лампа":
            check -= lamp

        elif shop == "брелок":
            check -= keychain

        else:
            print("Такого товара немає ")

    elif menu == 3:
        check = 0
        goods = ""
        print("Кошик очіщен")

    elif menu == 4:
        print()
        print(f"Ви обрали: \n{goods}, \nСумма Вашої покупки {check} грн")

    else:
        print("Невірний вибір. Будь ласка, виберіть від 1 до 5.")
